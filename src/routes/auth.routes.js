const router = require("express").Router();
const auth = require("../middleware/auth");
const wrap = require("../utils/async-response");
const controller = require("../controllers/auth.controller");
const { validate } = require("../middleware/validate");
const { auth: schemas } = require("../validation/schemas");
router.post("/register", validate({ body: schemas.register }), wrap(controller.register));
router.post("/login", validate({ body: schemas.login }), wrap(controller.login));
router.get("/me", auth, controller.getMe);
router.put("/change-password", auth, validate({ body: schemas.changePassword }), wrap(controller.changePassword));
router.put("/reset-password", auth, validate({ body: schemas.resetPassword }), wrap(controller.resetPassword));
module.exports = router;
